"""Generate the C-style API from the vendored raylib 6.0 parser output."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
raw = (ROOT / 'gen/raylib_api.json').read_text()
# Upstream's JSON writer does not escape embedded quotes in descriptions.
raw = re.sub(r'("description": )"(.*)"(,?)$',
             lambda m: m[1] + json.dumps(m[2]) + m[3], raw, flags=re.M)
api = json.loads(raw)
base = {'void': 'Cvoid', 'bool': 'Bool', 'char': 'Cchar',
        'unsigned char': 'Cuchar', 'unsigned short': 'Cushort',
        'int': 'Cint', 'unsigned int': 'Cuint', 'long': 'Clong',
        'float': 'Cfloat', 'double': 'Cdouble',
        'rAudioBuffer': 'Cvoid', 'rAudioProcessor': 'Cvoid'}
base.update({c['name']: 'Ptr{Cvoid}' for c in api['callbacks']})

def typ(s, argument=False):
    s = s.replace('const ', '').strip()
    a = re.fullmatch(r'(.+)\[(\d+)\]', s)
    if a:
        return f'NTuple{{{a[2]}, {typ(a[1])}}}'
    if '*' in s:
        if argument and s == 'char *':
            return 'Cstring'
        return 'Ptr{' + typ(s.rsplit('*', 1)[0].strip()) + '}'
    return base.get(s, s)

out = ['# Generated by gen/generate.py; do not edit.']
names = []
aliases = list(api['aliases'])
for st in api['structs']:
    out += [f'struct {st["name"]}']
    out += [f'    {f["name"]}::{typ(f["type"])}' for f in st['fields']]
    out += ['end', '']
    names.append(st['name'])
    # Emit aliases as soon as their underlying struct is available.
    for a in aliases[:]:
        if a['type'] == st['name']:
            n = a['name'].lstrip('*')
            t = f'Ptr{{{st["name"]}}}' if a['name'].startswith('*') else st['name']
            out.append(f'const {n} = {t}')
            names.append(n)
            aliases.remove(a)
for en in api['enums']:
    for v in en['values']:
        out.append(f'const {v["name"]} = Cint({v["value"]})')
        names.append(v['name'])
for d in api['defines']:
    if d['type'] == 'COLOR':
        vals = re.search(r'\{(.*)\}', d['value'])[1]
        out.append(f'const {d["name"]} = Color({vals})')
        names.append(d['name'])
skipped = []
for fn in api['functions']:
    ps = fn.get('params', [])
    if any(p['type'] == '...' for p in ps):
        skipped.append(fn['name'])
        continue
    n = fn['name']
    args = [f'a{i}' for i in range(len(ps))]
    ts = [typ(p['type'], argument=True) for p in ps]
    out += [f'function {n}({", ".join(args)})',
            f'    ccall((:{n}, libraylib), {typ(fn["returnType"])}, ({", ".join(ts)}{"," if len(ts)==1 else ""}), {", ".join(args)})' if args else
            f'    ccall((:{n}, libraylib), {typ(fn["returnType"])}, ())', 'end']
    names.append(n)
out.append('export ' + ', '.join(names))
(ROOT / 'src/bindings.jl').write_text('\n'.join(out) + '\n')
print(f'Generated {len(api["functions"]) - len(skipped)} functions; variadic exclusions: {skipped}')

probe = ['#include <stddef.h>', '#include <stdio.h>', '#include "raylib.h"', 'int main(void) {']
for st in api['structs']:
    n = st['name']
    probe.append(f'printf("{n} %zu", sizeof({n}));')
    for field in st['fields']:
        probe.append(f'printf(" %zu", offsetof({n}, {field["name"]}));')
    probe.append('puts("");')
probe.append('return 0; }')
(ROOT / 'test/abi.c').write_text('\n'.join(probe) + '\n')
